-- Beneficiaries can read grant events for their own grants
DROP POLICY IF EXISTS "beneficiary_read_own_grant_events" ON public.sponsored_grant_events;
CREATE POLICY "beneficiary_read_own_grant_events" ON public.sponsored_grant_events
    FOR SELECT
    USING (
        grant_id IN (
            SELECT sg.id
            FROM public.sponsored_grants sg
            WHERE
                (sg.beneficiary_type = 'SCHOOL'
                    AND sg.beneficiary_id::TEXT = current_setting('request.jwt.claim.tenantId', true))
                OR
                (sg.beneficiary_type = 'INDEPENDENT_LEARNER'
                    AND sg.beneficiary_id IN (
                        SELECT id FROM public.independent_learners
                        WHERE user_id::TEXT = current_setting('request.jwt.claim.sub', true)
                    ))
        )
    );

-- ─── 5. Helper RPC: increment_pool_remaining (used by grant revoke) ───────────

DROP FUNCTION IF EXISTS public.increment_pool_remaining(UUID, NUMERIC);
CREATE OR REPLACE FUNCTION public.increment_pool_remaining(p_pool_id UUID, p_amount NUMERIC)
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    UPDATE public.sponsorship_pools
    SET remaining_lkr = remaining_lkr + p_amount
    WHERE id = p_pool_id;
$$;

GRANT EXECUTE ON FUNCTION public.increment_pool_remaining(UUID, NUMERIC) TO service_role, authenticated;

