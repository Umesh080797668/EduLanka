    ADD CONSTRAINT sponsored_grant_events_event_type_check
    CHECK (event_type IN ('GRANTED', 'EXPIRY_WARNING', 'EXPIRED', 'MANUAL_REVOKE'));

-- ─── 2. RLS policies for public.sponsorship_pools ────────────────────────────

-- Super Admins (service_role JWT) can read all pools
DROP POLICY IF EXISTS "super_admin_read_pools" ON public.sponsorship_pools;
CREATE POLICY "super_admin_read_pools" ON public.sponsorship_pools
    FOR SELECT
    USING (
        current_setting('request.jwt.claim.role', true) = 'SUPER_ADMIN'
    );

-- Service role bypass (used by scheduled jobs / billing processor)
DROP POLICY IF EXISTS "service_role_manage_pools" ON public.sponsorship_pools;
CREATE POLICY "service_role_manage_pools" ON public.sponsorship_pools
    FOR ALL
    USING (auth.role() = 'service_role')
    WITH CHECK (auth.role() = 'service_role');

